#!/usr/bin/env python3
"""Generate the autonomous OpenCode model-routing contract from the registry."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".agents/skills/prompt-optimizer/references/model-registry.json"
JSON_OUTPUT = ROOT / "adapters/opencode/plugin/profile-contract.json"
TS_OUTPUT = ROOT / "adapters/opencode/plugin/model-registry.ts"
PI_OUTPUT = ROOT / "adapters/pi/extensions/model-registry.ts"


def load_profiles() -> list[dict[str, object]]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    profiles = data.get("profiles")
    if not isinstance(profiles, list) or not profiles:
        raise ValueError("model registry profiles must be a non-empty array")
    result: list[dict[str, object]] = []
    for item in profiles:
        if not isinstance(item, dict) or not isinstance(item.get("id"), str) or not isinstance(item.get("aliases"), list):
            raise ValueError(f"invalid model registry entry: {item!r}")
        result.append({"id": item["id"], "aliases": item["aliases"]})
    return result


def render_json(profiles: list[dict[str, object]]) -> str:
    return json.dumps({"schemaVersion": 1, "profiles": profiles}, ensure_ascii=False, indent=2) + "\n"


def render_ts(profiles: list[dict[str, object]]) -> str:
    ids = [str(item["id"]) for item in profiles]
    aliases: list[tuple[str, str]] = []
    for item in profiles:
        profile = str(item["id"])
        for alias in item["aliases"]:
            if not isinstance(alias, str):
                raise ValueError(f"invalid alias for {profile}: {alias!r}")
            aliases.append((alias, profile))
    lines = [
        "// Generated by tools/sync_model_registry.py; edit model-registry.json instead.",
        "export type Profile =",
        *[f'  | "{profile}"' for profile in ids],
        "",
        "export const PROFILE_IDS = [",
        *[f'  "{profile}",' for profile in ids],
        "] as const satisfies readonly Profile[]",
        "",
        "export const EXACT_MODEL_ALIASES: Record<string, Profile> = {",
        *[f'  "{alias}": "{profile}",' for alias, profile in aliases],
        "}",
        "",
    ]
    return "\n".join(lines)


def render_pi_ts(profiles: list[dict[str, object]]) -> str:
    aliases: list[tuple[str, str]] = []
    for item in profiles:
        for alias in item["aliases"]:
            if not isinstance(alias, str):
                raise ValueError(f"invalid alias for {item['id']}: {alias!r}")
            aliases.append((alias, str(item["id"])))
    lines = [
        "// Generated by tools/sync_model_registry.py; do not edit.",
        "export type Profile =",
        *[f'  | "{item["id"]}"' for item in profiles],
        "",
        "const EXACT_MODEL_ALIASES: Record<string, Profile> = {",
        *[f'  "{alias}": "{profile}",' for alias, profile in aliases],
        "}",
        "",
        "export function normalizeModelID(value: unknown): string {",
        '  return typeof value === "string" ? value.trim().toLowerCase().replace(/_/g, "-").split("/").at(-1) ?? "" : ""',
        "}",
        "",
        "export function resolvePiProfile(modelID: unknown): Profile | undefined {",
        "  const normalized = normalizeModelID(modelID)",
        '  const candidates = normalized.endsWith("-latest") ? [normalized.slice(0, -7), normalized] : [normalized]',
        "  for (const candidate of candidates) {",
        "    if (Object.hasOwn(EXACT_MODEL_ALIASES, candidate)) return EXACT_MODEL_ALIASES[candidate]",
        "  }",
        "  return undefined",
        "}",
        "",
    ]
    return "\n".join(lines)


def generated() -> tuple[str, str]:
    profiles = load_profiles()
    return render_json(profiles), render_ts(profiles)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated artifacts are stale")
    args = parser.parse_args()
    json_text, ts_text = generated()
    profiles = load_profiles()
    current = [(JSON_OUTPUT, json_text), (TS_OUTPUT, ts_text), (PI_OUTPUT, render_pi_ts(profiles))]
    stale = [path for path, expected in current if not path.is_file() or path.read_text(encoding="utf-8") != expected]
    if args.check:
        if stale:
            for path in stale:
                print(f"stale generated model registry artifact: {path}")
            return 1
        print("Model registry artifacts are up to date")
        return 0
    JSON_OUTPUT.write_text(json_text, encoding="utf-8")
    TS_OUTPUT.write_text(ts_text, encoding="utf-8")
    PI_OUTPUT.write_text(render_pi_ts(profiles), encoding="utf-8")
    print(f"Generated {JSON_OUTPUT}, {TS_OUTPUT}, and {PI_OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
